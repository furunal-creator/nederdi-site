  /* ─── Interpretation fetching ──────────────────────────── */
  function fetchInterpretation(newsId, philosopherId) {
    if (!INTERPRET_API) {
      return Promise.reject(new Error("API not configured"));
    }
    return fetch(INTERPRET_API, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ news_id: newsId, philosopher_id: philosopherId, lang: currentLang }),
    }).then(function (r) {
      if (r.status === 429) {
        throw new Error("RATE_LIMIT");
      }
      if (!r.ok) throw new Error("API error");
      return r.json();
    });
  }

  /* ─── Format date ──────────────────────────────────────── */
  function formatDate(dateStr) {
    var months = (currentLang === "en" ? EN : currentLang === "zh" ? ZH : TR).months;
    var parts = dateStr.split("-");
    var day = parseInt(parts[2], 10);
    var month = months[parseInt(parts[1], 10) - 1];
    var year = parts[0];
    if (currentLang === "en") return month + " " + day + ", " + year;
    if (currentLang === "zh") return year + "年" + month + day + "日";
    return day + " " + month + " " + year;
  }

