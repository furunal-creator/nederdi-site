  /* ─── Navigation ───────────────────────────────────────── */
  function updateNav(active) {
    var links = document.querySelectorAll(".header__nav-link");
    links.forEach(function (link) {
      var nav_key = link.getAttribute("data-nav");
      if (nav_key === active) {
        link.classList.add("header__nav-link--active");
      } else {
        link.classList.remove("header__nav-link--active");
      }
      if (nav_key === "haberler") link.textContent = t('nav_news');
      if (nav_key === "filozoflar") link.textContent = t('nav_philosophers');
      if (nav_key === "psikologlar") link.textContent = t('nav_psychologists');
      if (nav_key === "tarihciler") link.textContent = t('nav_historians');
    });

    /* Close mobile menu */
    var nav = document.getElementById("main-nav");
    nav.classList.remove("header__nav--open");
    var btn = document.getElementById("mobile-menu-btn");
    btn.innerHTML = '<svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M3 12h18M3 6h18M3 18h18"/></svg>';
  }

  /* ─── Router ───────────────────────────────────────────── */
  function route() {
    var hash = window.location.hash || "#/";
    window.scrollTo(0, 0);
    document.title = currentLang === "en" ? "Ne Derdi? \u2014 History's Great Thinkers Comment on Today" : currentLang === "zh" ? "他们会怎么说？\u2014 历史伟大思想家评论当今时事" : "Ne Derdi? \u2014 Tarihin B\u00fcy\u00fck D\u00fc\u015f\u00fcn\u00fcrleri G\u00fcn\u00fcm\u00fcz\u00fc Yorumluyor";
    if (hash === "#/filozoflar") {
      renderPhilosophersPage();
    } else if (hash === "#/psikologlar") {
      renderPsychologistsPage();
    } else if (hash === "#/tarihciler") {
      renderHistoriansPage();
    } else if (hash.indexOf("#/haber/") === 0) {
      var targetId = hash.replace("#/haber/", "");
      renderHomepage();
      setTimeout(function () {
        var el = document.querySelector('[data-news-id="' + targetId + '"]');
        if (el) el.scrollIntoView({ behavior: "smooth", block: "start" });
      }, 300);
    } else {
      renderHomepage();
    }
    var disc = document.getElementById("footer-disclaimer");
    if (disc) disc.textContent = t('disclaimer');
  }

  /* ─── Keyboard: close modals with Escape ───────────────── */
  document.addEventListener("keydown", function (e) {
    if (e.key === "Escape") {
      closeInterpretationModal();
      closePhilosopherDetailModal();
      closePsychologistDetailModal();
      closeHistorianDetailModal();
    }
  });

  /* ─── Init ─────────────────────────────────────────────── */
  window.addEventListener("hashchange", route);

  /* Try fetching fresh news from API, fallback to embedded data */
  if (NEWS_API) {
    fetch(NEWS_API)
      .then(function (r) {
        if (!r.ok) throw new Error("API error");
        return r.json();
      })
      .then(function (data) {
        if (data && data.length > 0) {
          newsItems = data;
          /* Rebuild maps in case new entries appeared */
          data.forEach(function (news) {
            if (news.philosopher_ids) {
              news.philosopher_ids.forEach(function (pid) {
                if (!philosophersMap[pid]) {
                  var found = PHILOSOPHERS_LIST.find(function (p) { return p.id === pid; });
                  if (found) philosophersMap[pid] = found;
                }
              });
            }
            if (news.historian_ids) {
              news.historian_ids.forEach(function (hid) {
                if (!historiansMap[hid]) {
                  var found = HISTORIANS_LIST.find(function (h) { return h.id === hid; });
                  if (found) historiansMap[hid] = found;
                }
              });
            }
          });
        }
        route();
      })
      .catch(function () {
        /* Use embedded fallback */
        route();
      });
  } else {
    route();
  }
